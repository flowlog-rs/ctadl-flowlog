#!/usr/bin/env python3
"""CTADL with a FlowLog backend: a drop-in replacement for the `ctadl` command.

    flowlog_ctadl.py --directory DIR index -f
    flowlog_ctadl.py --directory DIR query --compute-slices all

CTADL's own command-line driver does everything -- importing, model
generation, preprocessing, index metadata, query views, SARIF export --
except running the Datalog analysis. Instead of compiling the preprocessed
program with Souffle, it is translated to FlowLog (souffle2flowlog.py),
compiled with the FlowLog compiler (cached by content hash, as CTADL caches
its Souffle binaries) and executed. FlowLog's sqlite results are converted to
Souffle's layout (fl_db_adapter.py), so the index database stays compatible
with CTADL's Python tooling and with Souffle-based queries.

The name must not start with `ctadl_`: CTADL imports every top-level module
named `ctadl_*` as a plugin, and this script's directory is on sys.path.

Environment (the FlowLog defaults assume a checkout `flowlog/` next to the
CTADL checkout that holds this directory):
  CTADL_CLI              CTADL's `ctadl` script (default: `ctadl` on PATH)
  FLOWLOG_COMPILER       flowlog-compiler binary
                         (default: ../../flowlog/target/release/flowlog-compiler)
  FLOWLOG_RUNTIME_PATH   flowlog-runtime crate (default: ../../flowlog/flowlog-runtime)
  FLOWLOG_CTADL_CACHE    compiled analyses (default: ~/.cache/ctadl-flowlog)
  FLOWLOG_CTADL_POLICY   choice-domain policy file (default: policy.json next to
                         this script); part of the cache key
  FLOWLOG_CARGO_TARGET   cargo target dir shared by compilations
                         (default: $FLOWLOG_CTADL_CACHE/target)
  FLOWLOG_CTADL_TIMING   if set, print per-step timings to stderr
"""
from __future__ import annotations

import fcntl
import hashlib
import importlib.machinery
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import convert_facts  # noqa: E402
import fl_db_adapter  # noqa: E402
import souffle2flowlog  # noqa: E402

UDF = HERE / "ctadl_udf.rs"


def env_path(name: str, default: Path) -> Path:
    return Path(os.environ[name]) if os.environ.get(name) else default


POLICY = env_path("FLOWLOG_CTADL_POLICY", HERE / "policy.json")
COMPILER = env_path("FLOWLOG_COMPILER", HERE.parent.parent / "flowlog/target/release/flowlog-compiler")
RUNTIME = env_path("FLOWLOG_RUNTIME_PATH", HERE.parent.parent / "flowlog/flowlog-runtime")
CACHE = env_path("FLOWLOG_CTADL_CACHE", Path.home() / ".cache/ctadl-flowlog")
CARGO_TARGET = env_path("FLOWLOG_CARGO_TARGET", CACHE / "target")
TIMING = bool(os.environ.get("FLOWLOG_CTADL_TIMING"))


def timing(step: str, t0: float) -> float:
    t1 = time.time()
    if TIMING:
        print(f"[flowlog] {step}: {t1 - t0:.2f}s", file=sys.stderr)
    return t1


def load_ctadl_cli():
    path = os.environ.get("CTADL_CLI") or shutil.which("ctadl")
    if not path:
        sys.exit("error: cannot find CTADL's `ctadl` script; set CTADL_CLI")
    loader = importlib.machinery.SourceFileLoader("ctadl_cli", path)
    spec = importlib.util.spec_from_loader("ctadl_cli", loader)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["ctadl_cli"] = mod
    loader.exec_module(mod)
    return mod


def cache_key(src: Path) -> str:
    h = hashlib.sha256()
    for p in (src, POLICY, UDF, HERE / "souffle2flowlog.py"):
        h.update(p.read_bytes())
        h.update(b"\0")
    st = COMPILER.stat()
    h.update(f"{COMPILER.resolve()}:{st.st_size}:{st.st_mtime_ns}:{RUNTIME.resolve()}".encode())
    return h.hexdigest()[:32]


class FlowLogAnalysis:
    """Stands in for CTADL's SouffleCompiledAnalysis."""

    def __init__(self, cli, args, src: str):
        self.cli = cli
        self.dir = CACHE / cache_key(Path(src))
        self.fl = self.dir / "program.fl"
        self.schema_path = self.dir / "schema.json"
        self.bin = self.dir / "analysis"
        self.dir.mkdir(parents=True, exist_ok=True)
        with open(self.dir / ".lock", "w") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            if not self.bin.exists():
                self.build(Path(src))
        self.schema = json.loads(self.schema_path.read_text())

    def build(self, src: Path) -> None:
        cli = self.cli
        t0 = time.time()
        policy = json.loads(POLICY.read_text())
        try:
            items = souffle2flowlog.Parser(souffle2flowlog.lex(src.read_text())).parse_program()
            tr = souffle2flowlog.Translator(items, policy)
            text = "\n".join(souffle2flowlog.print_items(tr.run())) + "\n"
        except (souffle2flowlog.TranslateError, souffle2flowlog.ParseFail) as e:
            cli.error(f"error: translating '{src}' to FlowLog failed: {e}")
            sys.exit(1)
        self.fl.write_text(f"// Generated by souffle2flowlog.py from {src.resolve()}\n" + text)
        self.schema_path.write_text(json.dumps(tr.schema, indent=1))
        (self.dir / "translate.log").write_text("".join(f"warning: {w}\n" for w in tr.warnings))
        t0 = timing("translate", t0)
        cli.status(f"compiling FlowLog analysis to '{self.bin}' (takes a few minutes)...")
        cmd = [
            str(COMPILER), str(self.fl), "--str-intern", "--udf-file", str(UDF),
            "-o", str(self.bin) + ".tmp", "-B", str(self.dir / "build"), "-T", str(CARGO_TARGET),
        ]
        env = dict(os.environ, FLOWLOG_RUNTIME_PATH=str(RUNTIME))
        # A kept build dir (-B) makes FlowLog enable incremental compilation,
        # but each program gets its own content-addressed dir, so it is never
        # reused and would leave ~1 GB per program in the shared target dir.
        env.setdefault("CARGO_INCREMENTAL", "0")
        with open(self.dir / "compile.log", "w") as log:
            res = subprocess.run(cmd, env=env, stdout=log, stderr=subprocess.STDOUT)
        if res.returncode != 0:
            tail = (self.dir / "compile.log").read_text().splitlines()[-30:]
            cli.error("FlowLog compilation failed:\n" + "\n".join(tail))
            sys.exit(1)
        os.replace(str(self.bin) + ".tmp", self.bin)
        timing("compile", t0)

    def analyze(self, fact_dir, out_dir, args):
        cli = self.cli
        with tempfile.TemporaryDirectory(prefix="flowlog-", dir=args.tmpdir) as tmp:
            indir, outdir = Path(tmp) / "in", Path(tmp) / "out"
            indir.mkdir()
            outdir.mkdir()
            t0 = time.time()
            if fact_dir is not None:
                convert_facts.convert(self.fl, Path(fact_dir), indir, self.schema_path)
            for fname, rels in group_by_file(self.schema.get("inputs", [])).items():
                src_db = Path(fname)
                if fact_dir is not None and (Path(fact_dir) / fname).exists():
                    src_db = Path(fact_dir) / fname
                if not src_db.exists():
                    cli.error(f"error: input database does not exist: '{src_db}'")
                    sys.exit(1)
                counts = fl_db_adapter.to_flowlog(str(src_db), str(indir / fname), {"inputs": rels})
                missing = sorted(n for n, c in counts.items() if c < 0)
                if missing:
                    cli.warn(f"relations missing from '{src_db}', read as empty: {', '.join(missing)}")
            t0 = timing("prepare inputs", t0)
            cmd = [str(self.bin), "-F", str(indir), "-D", str(outdir), "-w", str(args.jobs)]
            cli.status(f"running FlowLog analysis with {args.jobs} workers", verb=1)
            quiet = cli.ctadl.verbosity <= 0 or args.quiet
            res = subprocess.run(cmd, capture_output=quiet, text=True)
            if res.returncode != 0:
                if quiet:
                    sys.stderr.write(res.stdout + res.stderr)
                cli.error(f"FlowLog analysis failed with exit code {res.returncode}")
                sys.exit(1)
            t0 = timing("FlowLog run", t0)
            if TIMING and quiet:
                # "<elapsed>: Dataflow executed": the rest of the run writes the results
                for line in res.stdout.splitlines():
                    print(f"[flowlog]   {line}", file=sys.stderr)
            for fname, rels in group_by_file(self.schema.get("outputs", [])).items():
                fl_db_adapter.to_souffle(str(outdir / fname), fname, {"outputs": rels}, append=True)
            timing("write results", t0)
            return res


def group_by_file(rels: list) -> dict:
    out: dict = defaultdict(list)
    for r in rels:
        out[r["file"]].append(r)
    return out


def main() -> None:
    cli = load_ctadl_cli()

    def build_analysis(args, src):
        return FlowLogAnalysis(cli, args, src)

    cli.build_analysis = build_analysis
    try:
        cli.main(sys.argv)
    except BrokenPipeError:
        pass


if __name__ == "__main__":
    main()
